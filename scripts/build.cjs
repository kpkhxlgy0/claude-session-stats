'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const renderer = fs.readFileSync(path.join(root, 'src/renderer.cjs'), 'utf8');
const entry = `// Generated by npm run build. Edit src/renderer.cjs or src/main.cjs.\n"use strict";\n`
    + `const renderer = (() => { const module = { exports: {} };\n${renderer}\nreturn module.exports; })();\n`
    + `let controller;\nmodule.exports = {\n`
    + `    start(api) {\n        module.exports.stop();\n`
    + `        if (api.process === "main") controller = require("./src/main.cjs").startMain(api);\n`
    + `        else if (api.process === "renderer") controller = renderer.startRenderer(api);\n    },\n`
    + `    stop() { controller?.stop(); controller = undefined; },\n};\n`;
if (process.argv.includes('--check')) {
    if (!fs.existsSync(path.join(root, 'index.js')) || fs.readFileSync(path.join(root, 'index.js'), 'utf8') !== entry)
        throw new Error('index.js is stale; run npm run build');
} else fs.writeFileSync(path.join(root, 'index.js'), entry);
